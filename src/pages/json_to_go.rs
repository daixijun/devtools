//! JSON 转 Go 结构体。
//!
//! 自动联动：输入或任意配置变化后 500ms 防抖调用 core 的同步纯函数
//! `convert_json_to_go(json_str, JsonToGoOptions)`（无需 core_rt）。
//! core 直接返回 Go 代码字符串，
//! 输出即返回值本身。

use std::collections::HashMap;
use std::time::Duration;

use gpui::{
    div, prelude::FluentBuilder as _, px, App, AppContext as _, Context, Entity, IntoElement,
    ParentElement as _, Styled as _, Window,
};
use gpui_component::{
    checkbox::Checkbox,
    input::{EditorState, InputEvent, InputState},
    ActiveTheme as _,
};

use crate::components::ui;
use devtools::i18n::t;
use devtools::tools::json_to_go::{convert_json_to_go, JsonToGoOptions};

/// 内置示例（嵌套 JSON，与历史版本一致）。
const EXAMPLE_JSON: &str = r#"{
  "user": {
    "id": 123,
    "name": "张三",
    "email": "zhangsan@example.com",
    "age": 30,
    "is_active": true,
    "created_at": "2023-01-15T10:30:00Z",
    "profile": {
      "avatar": "https://example.com/avatar.jpg",
      "bio": "一名资深的Go开发者",
      "location": "北京",
      "website": "https://zhangsan.dev"
    },
    "tags": ["golang", "backend", "microservices"],
    "metadata": {
      "last_login": "2023-12-20T14:25:30Z",
      "login_count": 157,
      "preferences": {
        "theme": "dark",
        "language": "zh-CN",
        "notifications": true
      }
    }
  }
}"#;

/// 标签 checkbox 顺序（与 core JsonToGoOptions::default 一致）。
const TAGS: [&str; 8] = ["json", "yaml", "gorm", "db", "sql", "toml", "env", "ini"];

/// 编辑器高度（窗口 1100×800，header + 两行配置 + 错误条余量）。
const EDITOR_HEIGHT: f32 = 400.0;

pub struct JsonToGo {
    /// JSON 输入（代码编辑器，json 语法高亮）。
    input: Entity<EditorState>,
    /// Go 结构体输出（代码编辑器，go 语法高亮；等宽字体保证字段列对齐）。
    output: Entity<EditorState>,
    struct_name: Entity<InputState>,
    exported_fields: bool,
    is_go_118_or_above: bool,
    is_go_124_or_above: bool,
    /// 与 TAGS 顺序对应的选中状态。
    tag_checked: [bool; 8],
    error: Option<String>,
    /// 防抖代次：新事件使旧定时任务失效。
    debounce_gen: usize,
}

impl JsonToGo {
    pub fn create_view(window: &mut Window, cx: &mut App) -> gpui::AnyView {
        cx.new(|cx| Self::new(window, cx)).into()
    }

    fn new(window: &mut Window, cx: &mut Context<Self>) -> Self {
        // 代码编辑器（Editor + syntect 高亮；Textarea 非等宽字体，Go 结构体的
        // 字段列对齐会失效）
        let input = cx.new(|cx| {
            EditorState::new(window, cx)
                .language("json")
                .placeholder(t("粘贴 JSON 数据，自动生成 Go 结构体…"))
        });
        let output = cx.new(|cx| EditorState::new(window, cx).language("go"));
        let struct_name = ui::new_input(window, cx);
        struct_name.update(cx, |state, cx| {
            state.set_value("AutoGenerated", window, cx);
            state.set_placeholder(t("结构体名称"), window, cx);
        });

        // JSON 输入变化 → 500ms 防抖转换
        cx.subscribe_in(&input, window, |this, _, event: &InputEvent, window, cx| {
            if matches!(event, InputEvent::Change) {
                this.schedule_convert(window, cx);
            }
        })
        .detach();
        // 结构体名称变化 → 同样防抖联动
        cx.subscribe_in(
            &struct_name,
            window,
            |this, _, event: &InputEvent, window, cx| {
                if matches!(event, InputEvent::Change) {
                    this.schedule_convert(window, cx);
                }
            },
        )
        .detach();

        Self {
            input,
            output,
            struct_name,
            exported_fields: true,
            is_go_118_or_above: true,
            is_go_124_or_above: false,
            tag_checked: [true, false, false, false, false, false, false, false],
            error: None,
            debounce_gen: 0,
        }
    }

    /// 输入或配置变化后 500ms 防抖（新事件重置代次，取消未触发的旧转换）。
    fn schedule_convert(&mut self, window: &mut Window, cx: &mut Context<Self>) {
        self.debounce_gen = self.debounce_gen.wrapping_add(1);
        let gen = self.debounce_gen;
        let bg = cx.background_executor().clone();
        cx.spawn_in(window, async move |this, cx| {
            bg.timer(Duration::from_millis(500)).await;
            let _ = this.update_in(cx, |this, window, cx| {
                if this.debounce_gen == gen {
                    this.convert(window, cx);
                }
            });
        })
        .detach();
    }

    /// 同步转换（core 纯函数）：输入空 → 清输出；出错 → 红条提示。
    fn convert(&mut self, window: &mut Window, cx: &mut Context<Self>) {
        let json = self.input.read(cx).value().to_string();
        if json.trim().is_empty() {
            self.error = None;
            self.output
                .update(cx, |out, cx| out.set_value("", window, cx));
            cx.notify();
            return;
        }
        let mut struct_name = self.struct_name.read(cx).value().to_string();
        if struct_name.trim().is_empty() {
            struct_name = "AutoGenerated".to_string();
        }
        let mut selected_tags = HashMap::new();
        for (i, tag) in TAGS.iter().enumerate() {
            selected_tags.insert(tag.to_string(), self.tag_checked[i]);
        }
        let options = JsonToGoOptions {
            struct_name,
            exported_fields: self.exported_fields,
            is_go_118_or_above: self.is_go_118_or_above,
            is_go_124_or_above: self.is_go_124_or_above,
            selected_tags,
        };
        match convert_json_to_go(&json, options) {
            Ok(code) => {
                self.error = None;
                self.output
                    .update(cx, |out, cx| out.set_value(code.as_str(), window, cx));
            }
            Err(e) => {
                self.error = Some(format!("{}: {e}", t("转换出错")));
            }
        }
        cx.notify();
    }

    fn load_example(&mut self, window: &mut Window, cx: &mut Context<Self>) {
        // set_value 不发 Change 事件，直接同步转换
        self.input
            .update(cx, |state, cx| state.set_value(EXAMPLE_JSON, window, cx));
        self.convert(window, cx);
    }

    fn clear(&mut self, window: &mut Window, cx: &mut Context<Self>) {
        self.input
            .update(cx, |state, cx| state.set_value("", window, cx));
        self.output
            .update(cx, |state, cx| state.set_value("", window, cx));
        self.error = None;
        self.debounce_gen = self.debounce_gen.wrapping_add(1); // 取消未触发的防抖转换
        cx.notify();
    }

    /// 配置区 checkbox（带 .label 的 gpui-component Checkbox）。
    fn option_checkbox(
        &self,
        id: &'static str,
        label: &'static str,
        checked: bool,
        cx: &mut Context<Self>,
        set: impl Fn(&mut Self, bool) + 'static,
    ) -> Checkbox {
        Checkbox::new(id)
            .label(label)
            .checked(checked)
            .on_click(cx.listener(move |this, checked: &bool, window, cx| {
                set(this, *checked);
                this.schedule_convert(window, cx);
                cx.notify();
            }))
    }

    fn render_config(&mut self, cx: &mut Context<Self>) -> gpui::Div {
        let this_checked = self.tag_checked;
        let exported = self.exported_fields;
        let go118 = self.is_go_118_or_above;
        let go124 = self.is_go_124_or_above;
        let struct_name = &self.struct_name;

        let mut tags_row = div().flex().flex_wrap().items_center().gap_3();
        for (i, tag) in TAGS.iter().enumerate() {
            tags_row = tags_row.child(
                Checkbox::new(("jsontogo-tag", i))
                    .label((*tag).to_string())
                    .checked(this_checked[i])
                    .on_click(cx.listener(move |this, checked: &bool, window, cx| {
                        this.tag_checked[i] = *checked;
                        this.schedule_convert(window, cx);
                        cx.notify();
                    })),
            );
        }

        div()
            .flex()
            .flex_col()
            .gap_2()
            .child(
                div()
                    .flex()
                    .flex_wrap()
                    .items_center()
                    .gap_4()
                    .child(ui::hfield(
                        t("结构体名称"),
                        gpui_component::input::Input::new(struct_name).w(px(256.)),
                        cx,
                    ))
                    .child(self.option_checkbox(
                        "jsontogo-exported",
                        t("导出字段"),
                        exported,
                        cx,
                        |this, v| {
                            this.exported_fields = v;
                        },
                    ))
                    .child(self.option_checkbox(
                        "jsontogo-go118",
                        "Go 1.18+ (any)",
                        go118,
                        cx,
                        |this, v| {
                            this.is_go_118_or_above = v;
                        },
                    ))
                    .child(self.option_checkbox(
                        "jsontogo-go124",
                        "Go 1.24+ (omitzero)",
                        go124,
                        cx,
                        |this, v| {
                            this.is_go_124_or_above = v;
                        },
                    )),
            )
            .child(ui::hfield(t("标签选择:"), tags_row, cx))
    }

    fn render_editors(&mut self, cx: &mut Context<Self>) -> gpui::Div {
        let theme = cx.theme().clone();
        // 左右分栏（等宽）：左 JSON 输入（可编辑），右 Go 输出（只读）。
        // 布局为「共享行」结构：标题一行、编辑器一行，而非两列各自堆叠——
        // 两列标题内容不同高（左列含按钮）时，列内堆叠会使两侧编辑器起始 Y 错开。
        div()
            .flex()
            .flex_col()
            .gap_1()
            .child(
                // 标题行：左列标题 + 示例/清空，右列标题（行高由按钮撑起，两侧共享）
                div()
                    .flex()
                    .gap_3()
                    .child(
                        div()
                            .flex()
                            .flex_1()
                            .min_w(px(0.))
                            .items_center()
                            .justify_between()
                            .child(
                                div()
                                    .text_size(px(13.))
                                    .font_weight(gpui::FontWeight::MEDIUM)
                                    .text_color(theme.colors.foreground)
                                    .child(t("JSON 输入")),
                            )
                            .child(
                                div()
                                    .flex()
                                    .items_center()
                                    .gap_2()
                                    .child(ui::secondary_button(
                                        "jsontogo-example",
                                        t("示例"),
                                        cx.listener(|this, _ev: &gpui::ClickEvent, window, cx| {
                                            this.load_example(window, cx);
                                        }),
                                    ))
                                    .child(ui::secondary_button(
                                        "jsontogo-clear",
                                        t("清空"),
                                        cx.listener(|this, _ev: &gpui::ClickEvent, window, cx| {
                                            this.clear(window, cx);
                                        }),
                                    )),
                            ),
                    )
                    .child(
                        div().flex().flex_1().min_w(px(0.)).items_center().child(
                            div()
                                .text_size(px(13.))
                                .font_weight(gpui::FontWeight::MEDIUM)
                                .text_color(theme.colors.foreground)
                                .child(t("Go 结构体输出")),
                        ),
                    ),
            )
            .child(
                // 编辑器行：两侧同一行，起始 Y 天然对齐
                div()
                    .flex()
                    .gap_3()
                    .child(
                        div()
                            .flex_1()
                            .min_w(px(0.))
                            .child(ui::code_edit_area(&self.input, EDITOR_HEIGHT)),
                    )
                    .child(
                        div()
                            .flex_1()
                            .min_w(px(0.))
                            .child(ui::code_result_area(&self.output, EDITOR_HEIGHT)),
                    ),
            )
    }
}

impl gpui::Render for JsonToGo {
    fn render(&mut self, _window: &mut Window, cx: &mut Context<Self>) -> impl IntoElement {
        ui::tool_page("jsontogo")
            .child(self.render_config(cx))
            .child(self.render_editors(cx))
            .when_some(self.error.clone(), |el, e| {
                el.child(ui::error_banner(&e, cx))
            })
    }
}
